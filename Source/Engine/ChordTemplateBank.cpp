juce::StringArray ChordTemplateBank::getProgressionNamesForGenre(int genreIndex)
{
    const int safeGenre = std::clamp(genreIndex, 0, kNumGenres - 1);
    const auto& presets = getPresetTable()[static_cast<size_t>(safeGenre)];

    juce::StringArray names;
    for (const auto& preset : presets)
    {
        names.add(preset.name);
    }
    return names;
}

juce::MidiMessageSequence ChordTemplateBank::createPresetSequence(
    int genreIndex,
    int progressionIndex,
    bool isEightBars,
    double ticksPerQuarterNote)
{
    const int safeGenre = std::clamp(genreIndex, 0, kNumGenres - 1);
    const int safeProg  = std::clamp(progressionIndex, 0, kNumPresetsPerGenre - 1);
    const auto& spec    = getPresetTable()[static_cast<size_t>(safeGenre)][static_cast<size_t>(safeProg)];

    juce::MidiMessageSequence seq;
    for (const auto& chord : spec.chords)
    {
        addBlockChordToSequence(
            seq,
            chord.notes,
            chord.startPpq,
            chord.durationPpq,
            chord.velocity,
            ticksPerQuarterNote
        );
    }

    if (isEightBars)
    {
        for (const auto& chord : spec.secondHalfChords)
        {
            addBlockChordToSequence(
                seq,
                chord.notes,
                chord.startPpq,
                chord.durationPpq,
                chord.velocity,
                ticksPerQuarterNote
            );
        }
    }

    seq.sort();
    seq.updateMatchedPairs();
    return seq;
}

juce::MidiMessageSequence ChordTemplateBank::createPresetSequence(
    int genreIndex,
    int progressionIndex,
    double ticksPerQuarterNote)
{
    return createPresetSequence(genreIndex, progressionIndex, false, ticksPerQuarterNote);
}

juce::StringArray ChordTemplateBank::getTemplateNames()
{
    return getProgressionNamesForGenre(0);
}

juce::MidiMessageSequence ChordTemplateBank::createTemplateSequence(
    TemplateId templateId,
    double ticksPerQuarterNote)
{
    switch (templateId)
    {
        case TemplateId::Jazz2516:              return createPresetSequence(0, 0, false, ticksPerQuarterNote);
        case TemplateId::NeoSoul4321:           return createPresetSequence(1, 0, false, ticksPerQuarterNote);
        case TemplateId::CityPopJustTheTwoOfUs: return createPresetSequence(2, 0, false, ticksPerQuarterNote);
        case TemplateId::CinematicPedalSus4:    return createPresetSequence(3, 0, false, ticksPerQuarterNote);
    }
    return createPresetSequence(0, 0, false, ticksPerQuarterNote);
}

